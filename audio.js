import { SAMPLE_MAP } from "./sample_list.js";
import * as midi from "./midi.js";

// The audio context is created on first use rather than when this module is
// loaded. Browsers log an autoplay policy warning for a context created before
// any user interaction, and it keeps this module loadable without Web Audio.
//
// On iOS this is more than a warning. A context built before the page has been
// touched starts out suspended, and Safari does not always let resume() bring
// it back afterwards. Nothing here may reach for the context off the back of a
// page load: see SampleManager, which downloads the kit as the page opens but
// holds off on decoding it until there is a context to decode it with.
let audio_ctx = null;

// Whether the context exists yet, for the code that has something useful to do
// when it doesn't rather than a reason to build one
function has_audio_ctx()
{
    return audio_ctx != null;
}

function get_audio_ctx()
{
    if (!audio_ctx)
    {
        // Create AudioContext with 44.1kHz sample rate
        audio_ctx = new AudioContext({ sampleRate: 44100 });

        // Say that this is something being listened to rather than a sound
        // effect over something else. Web Audio on iOS is "ambient" audio
        // unless it says otherwise, and ambient audio is silenced by the
        // ring/silent switch on the side of the phone: a track plays with the
        // level up and the transport running and no sound comes out, with
        // nothing on the page to say why. Declaring it as playback is what
        // takes it out of that category.
        //
        // Safari 16.4 and later. The property is missing everywhere else,
        // where the switch this works around doesn't exist either.
        if (navigator.audioSession)
            navigator.audioSession.type = 'playback';
    }

    return audio_ctx;
}

//============================================================================
// Sample library
//
// This maps between the three ways of referring to a sample: its index, its
// name, and the path of its file. Note that sample_list.js is generated by
// update_samples.py and is just the raw path-to-index map.
//============================================================================

// SAMPLE_MAP maps sample paths to indices. Sample indices are stable
// over time (see update_samples.py), so a path may be missing from
// disk while its index stays reserved. We index paths by their fixed
// index rather than by position, leaving holes for any such gaps.
const sample_paths = [];
const sample_names = [];
const name_to_idx = new Map();

for (let [sample_path, sample_idx] of Object.entries(SAMPLE_MAP))
{
    let sample_name = sample_path.match(/samples\/(.+)\.wav/)[1];
    console.assert(typeof sample_name == 'string');

    sample_paths[sample_idx] = sample_path;
    sample_names[sample_idx] = sample_name;
    name_to_idx.set(sample_name, sample_idx);
}

console.assert(sample_paths.length > 0);

// Number of sample slots (highest index + 1)
export const NUM_SAMPLES = sample_paths.length;

// Sample indices in alphabetical order by name, which is how the sample
// selection UI lists them. Index order won't do: an index is assigned when a
// sample is added and never changes afterwards, so it drifts away from
// alphabetical as samples come and go. sample_list.js is generated sorted by
// name (see update_samples.py), so its own order is the one we want.
export const SORTED_SAMPLE_IDXS = Object.values(SAMPLE_MAP);

// Guard the ordering we get from sample_list.js, so that a file that somehow
// isn't sorted shows up here instead of as a scrambled sample list in the UI
console.assert(
    SORTED_SAMPLE_IDXS.every((sample_idx, i) =>
        i == 0 || sample_names[SORTED_SAMPLE_IDXS[i - 1]] < sample_names[sample_idx]
    ),
    'sample_list.js is expected to be sorted by sample name'
);

// Sample indices are encoded using 9 bits when sharing a project through a
// URL (see SAMPLE_IDX_BITS in model.js), which caps the index space at 512
console.assert(NUM_SAMPLES <= 512);

// Get the index for a given sample name
export function get_sample_idx(sample_name)
{
    console.assert(name_to_idx.has(sample_name));
    return name_to_idx.get(sample_name);
}

// Get the name of a given sample index.
// Returns undefined if no sample is associated with the index.
export function get_sample_name(sample_idx)
{
    console.assert(typeof sample_idx == 'number');
    return sample_names[sample_idx];
}

// Get the file path of a given sample index.
// Returns undefined if no sample is associated with the index. That happens
// for an index that's reserved but has no file on disk, and also for an index
// coming from a shared URL that was encoded against a longer sample list.
export function get_sample_path(sample_idx)
{
    console.assert(typeof sample_idx == 'number');
    return sample_paths[sample_idx];
}

//============================================================================
// Sample loading and playback
//============================================================================

class SampleManager
{
    constructor()
    {
        // Audio buffers for the samples, indexed by sample index
        this.sample_bufs = Array(NUM_SAMPLES);

        // Samples that have been downloaded but not yet decoded, as they came
        // off the network. Decoding is what needs an audio context, and the
        // kit starts downloading as the page opens, which is before there can
        // be one (see get_audio_ctx). These wait here until there is.
        this.raw_bufs = Array(NUM_SAMPLES);

        // Fetches currently in flight, indexed by sample index. A buffer isn't
        // stored until it finishes decoding, so we need this to know that a
        // sample is already on its way and avoid downloading it twice.
        this.pending_fetches = Array(NUM_SAMPLES);
    }

    // Turn a downloaded sample into an audio buffer.
    //
    // decodeAudioData takes the array buffer it is given over, so the download
    // is dropped here rather than kept around emptied out. That also makes
    // this safe to call twice on the same sample: the second call finds
    // nothing left to do.
    decode_sample(sample_idx)
    {
        let array_buffer = this.raw_bufs[sample_idx];

        if (!array_buffer)
            return Promise.resolve();

        this.raw_bufs[sample_idx] = null;

        return get_audio_ctx().decodeAudioData(array_buffer)
            .then(audio_buffer => this.sample_bufs[sample_idx] = audio_buffer)
            .catch(err => console.error(err));
    }

    // Decode everything downloaded while there was no context to decode it
    // with, which on a cold load is the whole of the starting kit
    decode_fetched()
    {
        let decoding = [];

        for (let sample_idx = 0; sample_idx < NUM_SAMPLES; ++sample_idx)
        {
            if (this.raw_bufs[sample_idx])
                decoding.push(this.decode_sample(sample_idx));
        }

        return Promise.all(decoding);
    }

    // Fetch/download a sample by index.
    // Returns a promise that settles once the sample is loaded, or immediately
    // if it's already loaded or there is no sample behind this index. Callers
    // that just want the sample on its way can ignore it.
    fetch_sample(sample_idx)
    {
        // Check if the sample is already loaded
        if (this.sample_bufs[sample_idx])
            return Promise.resolve();

        // Check if the sample is already being loaded. A buffer isn't stored
        // until it finishes decoding, so this is what tells us a sample is
        // already on its way and keeps us from downloading it twice.
        if (this.pending_fetches[sample_idx])
            return this.pending_fetches[sample_idx];

        // Downloaded already, and waiting on a context rather than on the
        // network. Asking for it again is what decodes it once there is one,
        // and downloading it a second time would be the bug this avoids.
        if (this.raw_bufs[sample_idx])
        {
            return has_audio_ctx()?
                this.decode_sample(sample_idx) : Promise.resolve();
        }

        let sample_path = get_sample_path(sample_idx);

        // There may be no sample behind this index: it can be reserved for a
        // sample no longer on disk, or come from a URL that was shared when
        // the sample list was longer. Such a row simply stays silent.
        if (!sample_path)
            return Promise.resolve();

        console.log(`Fetching ${sample_path}`);

        // Clearing the pending fetch once it settles means that a sample whose
        // fetch failed will be retried the next time it's requested
        return this.pending_fetches[sample_idx] = fetch(sample_path)
        .then(response => response.arrayBuffer())
        .then(array_buffer =>
        {
            this.raw_bufs[sample_idx] = array_buffer;

            // Decoded now if there is a context, and left for init_web_audio
            // to pick up if there isn't. Building one here to decode into is
            // what would put a context on the page before it has been touched.
            if (has_audio_ctx())
                return this.decode_sample(sample_idx);
        })
        .catch(err => console.error(err))
        .finally(() => this.pending_fetches[sample_idx] = null);

        //
        // TODO: on failure, retry once or twice after a small delay?
        // function retry(num_tries)
        //
    }

    // Get the audio buffer for a sample
    get_buffer(sample_idx)
    {
        console.assert(typeof sample_idx == 'number');

        // This returns undefined if the sample is not yet loaded,
        // or if there is no sample behind this index
        return this.sample_bufs[sample_idx];
    }

    // Play a sample at a given time relative to the audio context clock.
    //
    // The stereo position runs from -1 for hard left to 1 for hard right, and
    // the gain is a multiplier with 1 for the sample as it was recorded, both
    // on the scale the nodes work on rather than the tenths and decibels the
    // model holds; Pattern.row_stereo_pan and Pattern.row_gain convert between
    // the two. A sample playing dead centre at full level is routed straight to
    // the destination, so the nodes these cost are only paid for by the rows
    // that were actually set.
    //
    // Returns whether a voice was started, which is what the cap on a step is
    // counted in: a row that makes no sound costs nothing (see queue_pat_cells).
    play_sample(sample_idx, start_time, dst_node, stereo_pan = 0, gain = 1, send = 0)
    {
        const buffer = this.get_buffer(sample_idx);

        // If the sample is not yet loaded, do nothing
        if (!buffer)
            return false;

        // A row pulled all the way down is silent, so there is nothing to play
        if (gain == 0)
            return false;

        // A row feeding the delay is tapped after its level and its panning, so
        // that its echoes sit where the row sits and come down with it as it is
        // turned down. That takes a panner even on a row sitting dead centre,
        // which a dry row does without: echoes arriving somewhere other than
        // where the sound they came from is would read as a second instrument
        // rather than as that one repeating.
        if (stereo_pan != 0 || send > 0)
        {
            const panner = get_audio_ctx().createStereoPanner();
            panner.pan.value = stereo_pan;
            panner.connect(dst_node);

            if (send > 0)
            {
                const send_node = get_audio_ctx().createGain();
                send_node.gain.value = send;
                send_node.connect(get_delay_input());
                panner.connect(send_node);
            }

            dst_node = panner;
        }

        if (gain != 1)
        {
            const gain_node = get_audio_ctx().createGain();
            gain_node.gain.value = gain;
            gain_node.connect(dst_node);
            dst_node = gain_node;
        }

        // Create a buffer source
        const source = get_audio_ctx().createBufferSource();
        source.buffer = buffer;
        source.connect(dst_node);

        // Start playback at the specified time on the audio context clock
        source.start(start_time);

        return true;
    }
}

const samples = new SampleManager();

// Request that a single sample be loaded, by index.
// Loading is asynchronous, and a sample already loaded is not fetched again.
// Returns a promise that settles once the sample is available.
export function fetch_sample(sample_idx)
{
    return samples.fetch_sample(sample_idx);
}

// Request the samples used by a pattern
export function fetch_pattern_samples(pattern)
{
    for (let sample_idx of pattern.sample_idxs)
        samples.fetch_sample(sample_idx);
}

// Request the samples used by every pattern of a project
export function fetch_project_samples(project)
{
    for (let pattern of project.patterns)
        fetch_pattern_samples(pattern);
}

